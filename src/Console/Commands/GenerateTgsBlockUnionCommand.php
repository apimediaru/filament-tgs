<?php

declare(strict_types=1);

namespace ApiMedia\Tgs\Console\Commands;

use ApiMedia\Tgs\Data\BlockRegistry;
use ApiMedia\Tgs\Data\UnknownBlockData;
use Illuminate\Console\Command;
use Illuminate\Support\Facades\File;
use ReflectionClass;
use Spatie\TypeScriptTransformer\Attributes\TypeScript;

class GenerateTgsBlockUnionCommand extends Command
{
    protected $signature = 'tgs:generate-block-union';

    protected $description = 'Generate the TgsBlock discriminated-union TS type from BlockRegistry.';

    /** Fully-qualified generated TS name, exactly as Spatie emits it (PHP namespace + #[TypeScript] leaf). */
    public static function tsName(string $class): string
    {
        $ref = new ReflectionClass($class);
        $attr = $ref->getAttributes(TypeScript::class)[0] ?? null;
        $leaf = $attr?->newInstance()->name ?? $ref->getShortName();
        $ns = str_replace('\\', '.', $ref->getNamespaceName()); // e.g. ApiMedia.Tgs.Data.Blocks

        return "{$ns}.{$leaf}";
    }

    public function handle(): int
    {
        $members = collect(BlockRegistry::map())
            ->values()
            ->map(fn (string $class) => self::tsName($class))
            ->sort()->values() // deterministic order → no spurious diffs across devs
            ->push(self::tsName(UnknownBlockData::class)) // open end of the union
            ->implode("\n    | ");

        // Dotted ambient namespace so references like `ApiMedia.Tgs.Data.Block`
        // resolve consistently with every other LiteralTypeScriptType reference. TS merges
        // this ambient declaration with laravel.d.ts.
        $contents = "// AUTO-GENERATED by `php artisan tgs:generate-block-union`. Do not edit.\n"
            ."declare namespace ApiMedia.Tgs.Data {\n"
            ."  export type Block =\n    | {$members};\n"
            ."}\n";

        File::ensureDirectoryExists(resource_path('types'));
        File::put(resource_path('types/tgs-blocks.d.ts'), $contents);

        $this->info('tgs-blocks.d.ts generated.');

        return self::SUCCESS;
    }
}
